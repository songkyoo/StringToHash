using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace StringToHash.Tests;

public class StringToHashGenerationTests
{
    [Test]
    public void NestedGenericHashClassUsesPathsAndPreservesOriginalHashInputs()
    {
        const string source =
            """
            using HashNames = global::StringToHashAttribute;

            namespace @event.Example
            {
                public partial class Controller<T> where T : System.IDisposable
                {
                    private const string ReadyPath = "Base Layer.Combat.class";

                    [HashNames(names: new[] { "Open", "open", "Base Layer.Open  Door", ReadyPath, "namespace.Open" })]
                    private static partial class Hashes
                    {
                    }

                    public int Read() =>
                        Hashes.Open + Hashes.open + Hashes.Base_Layer.Open__Door +
                        Hashes.Base_Layer.Combat.@class + Hashes.@namespace.Open;
                }
            }
            """;
        var (result, output) = GeneratorCompilation.Run(source);

        Assert.That(result.Diagnostics, Is.Empty);

        var generatedSource = result.GeneratedTrees.Single().GetText().ToString();

        Assert.That(generatedSource, Does.StartWith("// <auto-generated />"));
        Assert.That(generatedSource, Does.Contain("namespace @event.Example"));
        Assert.That(generatedSource, Does.Contain("partial class Controller<T>"));
        Assert.That(generatedSource, Does.Contain("""Open = global::UnityEngine.Animator.StringToHash("Open");"""));
        Assert.That(generatedSource, Does.Contain("""Open__Door = global::UnityEngine.Animator.StringToHash("Base Layer.Open  Door");"""));
        Assert.That(generatedSource, Does.Contain("""@class = global::UnityEngine.Animator.StringToHash("Base Layer.Combat.class");"""));
        Assert.That(generatedSource, Does.Contain("""Animator.StringToHash("namespace.Open");"""));
        Assert.That(generatedSource.Split("class Base_Layer").Length, Is.EqualTo(2));

        var errors = output.GetDiagnostics().Where(diagnostic => diagnostic.Severity == DiagnosticSeverity.Error);
        Assert.That(errors, Is.Empty);
    }

    [Test]
    public void HashClassesWithTheSameSimpleNameAndDifferentTypesHaveDistinctOutputs()
    {
        const string source =
            """
            [StringToHash("Global")]
            public static partial class Hashes { }

            [StringToHash("Generic")]
            public static partial class Hashes<T> { }

            namespace Game
            {
                [StringToHash("Qualified")]
                public static partial class Hashes { }
            }
            """;
        var (result, output) = GeneratorCompilation.Run(source);

        Assert.That(result.Diagnostics, Is.Empty);
        Assert.That(result.GeneratedTrees, Has.Length.EqualTo(3));

        var errors = output.GetDiagnostics().Where(diagnostic => diagnostic.Severity == DiagnosticSeverity.Error);

        Assert.That(errors, Is.Empty);
    }

    [Test]
    public void ContainingPartialTypeKindsArePreserved()
    {
        const string source =
            """
            public partial record Controller
            {
                public readonly partial struct Container
                {
                    public partial interface IWidget<T>
                    {
                        [StringToHash("Open")]
                        public static partial class Hashes { }
                    }
                }
            }
            """;
        var (result, output) = GeneratorCompilation.Run(source);

        Assert.That(result.Diagnostics, Is.Empty);
        Assert.That(result.GeneratedTrees, Has.Length.EqualTo(1));

        var errors = output.GetDiagnostics().Where(diagnostic => diagnostic.Severity == DiagnosticSeverity.Error);

        Assert.That(errors, Is.Empty);
    }

    [Test]
    public void FixingAnInvalidNameGeneratesSourceOnTheSameDriver()
    {
        const string source =
            """
            [StringToHash(" Open")]
            public static partial class Hashes { }
            """;
        var original = GeneratorCompilation.CreateCompilation(source, LanguageVersion.CSharp9);
        var driver = GeneratorCompilation.CreateDriver(LanguageVersion.CSharp9).RunGenerators(original);
        var firstResult = driver.GetRunResult();

        Assert.That(firstResult.Diagnostics.Single().Id, Is.EqualTo("STH0006"));
        Assert.That(firstResult.GeneratedTrees, Is.Empty);

        var originalTree = original.SyntaxTrees.First();
        var correctedSource = source.Replace("\" Open\"", "\"Open\"");
        var correctedTree = CSharpSyntaxTree.ParseText(correctedSource, (CSharpParseOptions)originalTree.Options);
        var corrected = original.ReplaceSyntaxTree(originalTree, correctedTree);
        var correctedDriver = driver.RunGeneratorsAndUpdateCompilation(corrected, out var output, out _);
        var correctedResult = correctedDriver.GetRunResult();

        Assert.That(correctedResult.Diagnostics, Is.Empty);
        Assert.That(correctedResult.GeneratedTrees, Has.Length.EqualTo(1));

        var errors = output.GetDiagnostics().Where(diagnostic => diagnostic.Severity == DiagnosticSeverity.Error);

        Assert.That(errors, Is.Empty);
    }
}
