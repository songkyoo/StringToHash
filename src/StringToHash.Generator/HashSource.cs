using System.Security.Cryptography;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace StringToHash.Generator;

internal static class HashSource
{
    private static readonly SymbolDisplayFormat NamespaceFormat = SymbolDisplayFormat
        .FullyQualifiedFormat
        .WithGlobalNamespaceStyle(SymbolDisplayGlobalNamespaceStyle.Omitted);

    public static string GetHintName(INamedTypeSymbol targetType)
    {
        // 제네릭 타입과 중첩 타입을 구분하고 파일 이름 길이를 일정하게 유지한다.
        var typeName = targetType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        using var hash = SHA256.Create();
        var digest = hash.ComputeHash(Encoding.UTF8.GetBytes(typeName));

        return "StringToHash." + BitConverter.ToString(digest).Replace("-", "") + ".g.cs";
    }

    public static string Write(
        INamespaceSymbol namespaceSymbol,
        TypeDeclarationSyntax[] declarations,
        IEnumerable<HashMember> members
    )
    {
        var source = new StringBuilder("// <auto-generated />\n");
        var depth = 0;

        if (!namespaceSymbol.IsGlobalNamespace)
        {
            OpenBlock(source, "namespace " + namespaceSymbol.ToDisplayString(NamespaceFormat), ref depth);
        }

        foreach (var declaration in declarations)
        {
            OpenBlock(source, GetPartialDeclaration(declaration), ref depth);
        }

        WriteMembers(source, members, ref depth);

        while (depth > 0)
        {
            CloseBlock(source, ref depth);
        }

        return source.ToString();
    }

    private static string GetPartialDeclaration(TypeDeclarationSyntax declaration)
    {
        var header = new StringBuilder("partial ").Append(declaration.Keyword.Text);

        if (declaration is RecordDeclarationSyntax record
            && record.ClassOrStructKeyword.IsKind(SyntaxKind.StructKeyword)
        )
        {
            header.Append(" struct");
        }

        header.Append(' ').Append(declaration.Identifier.Text);

        if (declaration.TypeParameterList is { } parameters)
        {
            var parameterNames = parameters.Parameters.Select(parameter =>
            {
                return parameter.VarianceKeyword.IsKind(SyntaxKind.None)
                    ? parameter.Identifier.Text
                    : parameter.VarianceKeyword.Text + " " + parameter.Identifier.Text;
            });

            header.Append('<').Append(string.Join(", ", parameterNames)).Append('>');
        }

        return header.ToString();
    }

    private static void WriteMembers(StringBuilder source, IEnumerable<HashMember> members, ref int depth)
    {
        foreach (var member in members)
        {
            var identifier = EscapeIdentifier(member.MemberName);

            if (member is HashField field)
            {
                var hashInput = SymbolDisplay.FormatLiteral(field.HashInput, quote: true);

                AppendLine(
                    source,
                    $"public static readonly int {identifier} = global::UnityEngine.Animator.StringToHash({hashInput});",
                    depth
                );
            }
            else if (member is HashClass nestedClass)
            {
                OpenBlock(source, "public static class " + identifier, ref depth);
                WriteMembers(source, nestedClass.Members.Values, ref depth);
                CloseBlock(source, ref depth);
            }
        }

        #region Local Functions
        static string EscapeIdentifier(string name)
        {
            return SyntaxFacts.GetKeywordKind(name) == SyntaxKind.None ? name : "@" + name;
        }
        #endregion
    }

    private static void OpenBlock(StringBuilder source, string header, ref int depth)
    {
        AppendLine(source, header, depth);
        AppendLine(source, "{", depth);

        depth++;
    }

    private static void CloseBlock(StringBuilder source, ref int depth)
    {
        depth--;

        AppendLine(source, "}", depth);
    }

    private static void AppendLine(StringBuilder source, string text, int depth)
    {
        source.Append(' ', depth * 4).Append(text).Append('\n');
    }
}
